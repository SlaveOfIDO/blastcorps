#include "asm_helper.h"

.include "macro.inc"

#define MI_INTR_MASK ((1 << 6) - 1)

#define XOR_VALUE ~0

#define RO_MOVE t1

.globl __osRcpImTable

.text
.set noreorder
LEAF(osSetIntMask)
    mfc0 RO_MOVE, C0_SR

    andi v0, RO_MOVE, OS_IM_CPU
    lw t2, PHYS_TO_K1(MI_INTR_MASK_REG)
    sll t2, t2,0x10
    or v0, v0,t2

    and t0, a0, MI_INTR_MASK<<0x10
    srl t0, t0,0xf
    lhu t2, __osRcpImTable(t0)
    sw t2, PHYS_TO_K1(MI_INTR_MASK_REG)

    andi t0, a0, OS_IM_CPU
    and RO_MOVE, RO_MOVE, ~SR_IMASK
    or RO_MOVE, RO_MOVE,t0

    mtc0 RO_MOVE, C0_SR
    nop
    nop
    jr ra
    nop
END(osSetIntMask)

